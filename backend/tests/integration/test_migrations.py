"""Upgrade/downgrade against the fixture's disposable PostgreSQL database only."""

import os
import subprocess
import sys
from pathlib import Path
from uuid import uuid4

import pytest
from alembic import command
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.util.exc import AutogenerateDiffsDetected, CommandError
from sqlalchemy import inspect, text

from app.db.session import Database

pytestmark = pytest.mark.postgres
CONFIG_PATH = Path(__file__).resolve().parents[2] / "alembic.ini"


def test_deletion_migration_preserves_money_and_refuses_to_revive_removed_rows(postgres_settings):
    database = Database(postgres_settings)
    try:
        with database.engine.begin() as connection:
            config = Config(str(CONFIG_PATH))
            config.attributes["connection"] = connection
            command.upgrade(config, "0009_transaction_requests")
            owner, account, category, movement = [uuid4() for _ in range(4)]
            connection.execute(
                text(
                    "INSERT INTO users(id,name,email,password_hash) "
                    "VALUES (:id,'Synthetic','migration-delete@example.test','synthetic')"
                ),
                {"id": owner},
            )
            connection.execute(
                text(
                    "INSERT INTO accounts(id,user_id,name,type,opening_balance,opening_date) "
                    "VALUES (:id,:owner,'Synthetic','checking',1000,'2026-01-01')"
                ),
                {"id": account, "owner": owner},
            )
            connection.execute(
                text(
                    "INSERT INTO categories(id,user_id,name,type) "
                    "VALUES (:id,:owner,'Synthetic','expense')"
                ),
                {"id": category, "owner": owner},
            )
            connection.execute(
                text(
                    "INSERT INTO transactions(id,user_id,account_id,category_id,description,"
                    "amount,type,status,effective_date) VALUES "
                    "(:id,:owner,:account,:category,'Synthetic',150.10,'expense','posted','2026-01-02')"
                ),
                {"id": movement, "owner": owner, "account": account, "category": category},
            )
            before = connection.execute(
                text("SELECT id,amount,status,effective_date FROM transactions WHERE id=:id"),
                {"id": movement},
            ).one()
            command.upgrade(config, "head")
            assert (
                connection.execute(
                    text("SELECT deleted_at FROM transactions WHERE id=:id"), {"id": movement}
                ).scalar_one()
                is None
            )
            assert (
                connection.execute(
                    text("SELECT id,amount,status,effective_date FROM transactions WHERE id=:id"),
                    {"id": movement},
                ).one()
                == before
            )
            connection.execute(
                text("UPDATE transactions SET deleted_at=now() WHERE id=:id"), {"id": movement}
            )
            with pytest.raises(CommandError), connection.begin_nested():
                command.downgrade(config, "0009_transaction_requests")
            assert (
                MigrationContext.configure(connection).get_current_revision()
                == "0010_transaction_deletion"
            )
            assert connection.execute(
                text("SELECT deleted_at IS NOT NULL FROM transactions WHERE id=:id"),
                {"id": movement},
            ).scalar_one()
            command.check(config)
            # Only this synthetic fixture is restored to exercise the safe empty-marker downgrade.
            connection.execute(
                text("UPDATE transactions SET deleted_at=NULL WHERE id=:id"), {"id": movement}
            )
            command.downgrade(config, "0009_transaction_requests")
            assert (
                connection.execute(
                    text("SELECT id,amount,status,effective_date FROM transactions WHERE id=:id"),
                    {"id": movement},
                ).one()
                == before
            )
            command.upgrade(config, "head")
            command.check(config)
            command.downgrade(config, "base")
    finally:
        database.dispose()


def test_upgrade_is_repeatable_downgrade_preserves_data_and_check_detects_drift(postgres_settings):
    database = Database(postgres_settings)
    try:
        with database.engine.begin() as connection:
            config = Config(str(CONFIG_PATH))
            config.attributes["connection"] = connection
            assert inspect(connection).get_table_names() == []
            command.upgrade(config, "head")
            command.upgrade(config, "head")
            assert (
                MigrationContext.configure(connection).get_current_revision()
                == "0010_transaction_deletion"
            )
            assert set(inspect(connection).get_table_names()) == {
                "alembic_version",
                "accounts",
                "account_creation_requests",
                "categories",
                "financial_goals",
                "goal_allocations",
                "refresh_token_history",
                "import_jobs",
                "import_rows",
                "transactions",
                "transaction_creation_requests",
                "transfers",
                "users",
                "user_sessions",
            }
            command.check(config)

            # A synthetic table proves drift detection and preservation on rollback.
            connection.exec_driver_sql("CREATE TABLE migration_probe (marker text NOT NULL)")
            connection.execute(
                text("INSERT INTO migration_probe VALUES (:marker)"), {"marker": "synthetic"}
            )
            with pytest.raises(AutogenerateDiffsDetected):
                command.check(config)
            command.downgrade(config, "base")
            assert MigrationContext.configure(connection).get_current_revision() is None
            assert connection.execute(text("SELECT marker FROM migration_probe")).scalar_one() == (
                "synthetic"
            )
            connection.exec_driver_sql("DROP TABLE migration_probe")
            command.upgrade(config, "head")
            command.check(config)
            command.downgrade(config, "base")
            assert (
                connection.execute(text("SELECT count(*) FROM alembic_version")).scalar_one() == 0
            )
    finally:
        database.dispose()


def test_cli_targets_only_the_temporary_database_from_an_unrelated_directory(
    postgres_settings, tmp_path
):
    environment = dict(os.environ)
    for field in ("host", "port", "name", "user", "connect_timeout", "statement_timeout_ms"):
        environment[f"FINSIGHT_DB_{field.upper()}"] = str(getattr(postgres_settings, f"db_{field}"))
    environment["FINSIGHT_ENVIRONMENT"] = "test"
    password = postgres_settings.db_password.get_secret_value()
    environment["FINSIGHT_DB_PASSWORD"] = password
    for arguments in (
        ["upgrade", "head"],
        ["current"],
        ["check"],
        ["downgrade", "base"],
    ):
        result = subprocess.run(
            [sys.executable, "-m", "alembic", "-c", str(CONFIG_PATH), *arguments],
            cwd=tmp_path,
            env=environment,
            capture_output=True,
            text=True,
            timeout=20,
        )
        # Never include captured output in assertions: it could contain driver details.
        assert result.returncode == 0
        if password in result.stdout + result.stderr:
            pytest.fail("Migration CLI exposed a database secret", pytrace=False)
        if arguments == ["current"]:
            assert "0010_transaction_deletion (head)" in result.stdout

    environment["FINSIGHT_DB_PASSWORD"] = "synthetic-invalid-migration-password"
    result = subprocess.run(
        [sys.executable, "-m", "alembic", "-c", str(CONFIG_PATH), "current"],
        cwd=tmp_path,
        env=environment,
        capture_output=True,
        text=True,
        timeout=20,
    )
    assert result.returncode != 0
    output = result.stdout + result.stderr
    assert "check database configuration and availability" in output
    assert "synthetic-invalid-migration-password" not in output
    assert "Traceback" not in output
    if password in output:
        pytest.fail("Migration CLI exposed a database secret", pytrace=False)
