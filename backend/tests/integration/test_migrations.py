"""Upgrade/downgrade against the fixture's disposable PostgreSQL database only."""

import os
import subprocess
import sys
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect, text

from app.db.session import Database

pytestmark = pytest.mark.postgres
CONFIG_PATH = Path(__file__).resolve().parents[2] / "alembic.ini"


def test_upgrade_is_repeatable_downgrade_preserves_data_and_check_detects_drift(postgres_settings):
    database = Database(postgres_settings)
    try:
        with database.engine.begin() as connection:
            config = Config(str(CONFIG_PATH))
            config.attributes["connection"] = connection
            assert inspect(connection).get_table_names() == []
            command.upgrade(config, "head")
            command.upgrade(config, "head")
            assert MigrationContext.configure(connection).get_current_revision() == "0004_imports"
            assert set(inspect(connection).get_table_names()) == {
                "alembic_version",
                "accounts",
                "categories",
                "import_jobs",
                "import_rows",
                "users",
                "user_sessions",
            }
            command.check(config)

            # A synthetic table proves drift detection and preservation on rollback.
            connection.exec_driver_sql("CREATE TABLE migration_probe (marker text NOT NULL)")
            connection.execute(
                text("INSERT INTO migration_probe VALUES (:marker)"), {"marker": "synthetic"}
            )
            with pytest.raises(AutogenerateDiffsDetected):
                command.check(config)
            command.downgrade(config, "base")
            assert MigrationContext.configure(connection).get_current_revision() is None
            assert connection.execute(text("SELECT marker FROM migration_probe")).scalar_one() == (
                "synthetic"
            )
            connection.exec_driver_sql("DROP TABLE migration_probe")
            command.upgrade(config, "head")
            command.check(config)
            command.downgrade(config, "base")
            assert (
                connection.execute(text("SELECT count(*) FROM alembic_version")).scalar_one() == 0
            )
    finally:
        database.dispose()


def test_cli_targets_only_the_temporary_database_from_an_unrelated_directory(
    postgres_settings, tmp_path
):
    environment = dict(os.environ)
    for field in ("host", "port", "name", "user", "connect_timeout", "statement_timeout_ms"):
        environment[f"FINSIGHT_DB_{field.upper()}"] = str(getattr(postgres_settings, f"db_{field}"))
    environment["FINSIGHT_ENVIRONMENT"] = "test"
    password = postgres_settings.db_password.get_secret_value()
    environment["FINSIGHT_DB_PASSWORD"] = password
    for arguments in (
        ["upgrade", "head"],
        ["current"],
        ["check"],
        ["downgrade", "base"],
    ):
        result = subprocess.run(
            [sys.executable, "-m", "alembic", "-c", str(CONFIG_PATH), *arguments],
            cwd=tmp_path,
            env=environment,
            capture_output=True,
            text=True,
            timeout=20,
        )
        # Never include captured output in assertions: it could contain driver details.
        assert result.returncode == 0
        if password in result.stdout + result.stderr:
            pytest.fail("Migration CLI exposed a database secret", pytrace=False)
        if arguments == ["current"]:
            assert "0004_imports (head)" in result.stdout

    environment["FINSIGHT_DB_PASSWORD"] = "synthetic-invalid-migration-password"
    result = subprocess.run(
        [sys.executable, "-m", "alembic", "-c", str(CONFIG_PATH), "current"],
        cwd=tmp_path,
        env=environment,
        capture_output=True,
        text=True,
        timeout=20,
    )
    assert result.returncode != 0
    output = result.stdout + result.stderr
    assert "check database configuration and availability" in output
    assert "synthetic-invalid-migration-password" not in output
    assert "Traceback" not in output
    if password in output:
        pytest.fail("Migration CLI exposed a database secret", pytrace=False)
